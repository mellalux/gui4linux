#!/usr/bin/env python3
"""Generate src/font_data.h from a Linux console PSF1/PSF2 8x16 font.

Usage: tools/gen_font.py /usr/share/consolefonts/Uni2-Terminus16.psf.gz > src/font_data.h
"""
import gzip
import struct
import sys


def load(path):
    raw = open(path, 'rb').read()
    if raw[:2] == b'\x1f\x8b':
        raw = gzip.decompress(raw)
    if raw[:2] == b'\x36\x04':
        mode, size = raw[2], raw[3]
        n = 512 if mode & 1 else 256
        hdr, w, h = 4, 8, size
        has_table = bool(mode & 6)
        psf2 = False
    elif raw[:4] == b'\x72\xb5\x4a\x86':
        _, _, hdr, flags, n, size, h, w = struct.unpack('<8I', raw[:32])
        has_table = bool(flags & 1)
        psf2 = True
    else:
        sys.exit('not a PSF font')
    if w != 8 or h != 16:
        sys.exit('need an 8x16 font, got %dx%d' % (w, h))
    glyphs = [raw[hdr + i * size: hdr + (i + 1) * size] for i in range(n)]
    table = {}
    if has_table:
        pos = hdr + n * size
        for gi in range(n):
            if psf2:
                end = raw.index(b'\xff', pos)
                ent = raw[pos:end]
                pos = end + 1
                seqs = ent.split(b'\xfe')[0]
                cps = [ord(c) for c in seqs.decode('utf-8', 'ignore')]
            else:
                cps = []
                while True:
                    v = struct.unpack_from('<H', raw, pos)[0]
                    pos += 2
                    if v == 0xFFFF:
                        break
                    if v == 0xFFFE:  # combining sequence: skip to terminator
                        while struct.unpack_from('<H', raw, pos)[0] != 0xFFFF:
                            pos += 2
                        pos += 2
                        break
                    cps.append(v)
            for cp in cps:
                table.setdefault(cp, gi)
    else:
        for i in range(min(n, 256)):
            table[i] = i
    return glyphs, table


def wanted(cp):
    return (0x20 <= cp <= 0x7e or 0xa0 <= cp <= 0x17f or cp in (0x20ac, 0x2022, 0x2026, 0x2013, 0x2014, 0xfffd)
            or 0x2190 <= cp <= 0x2193 or 0x2500 <= cp <= 0x259f or 0x25a0 <= cp <= 0x25cf)


def main():
    glyphs, table = load(sys.argv[1])
    cps = sorted(cp for cp in table if wanted(cp))
    print('/* Generated by tools/gen_font.py from %s - do not edit. */' % sys.argv[1].split('/')[-1])
    print('static const uint32_t font_cps[%d] = {' % len(cps))
    for i in range(0, len(cps), 8):
        print('    ' + ', '.join('0x%x' % c for c in cps[i:i + 8]) + ',')
    print('};')
    print('static const uint8_t font_bits[%d][16] = {' % len(cps))
    for c in cps:
        print('    {' + ','.join('0x%02x' % b for b in glyphs[table[c]]) + '},')
    print('};')


main()
